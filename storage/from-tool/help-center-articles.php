<p>KURZ：冷烫先精确施加胶黏剂，再转移装饰层并固化；可表现精细细节、网点、大面积和叠印。</p>
<p>Duplo：局部 UV 使用 UV 固化光油；生产需要黑白硬边蒙版，不应包含渐变或柔边。</p>
<p>本指南中的 0.30 mm、0.40-0.50 mm 等为降低名片生产风险的建议起点，不是厂商统一设备极限。</p>
